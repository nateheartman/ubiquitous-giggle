describe('formulas written before the Notion syntax', () => {
  test.each(GOLDEN)('%s', (src, expected) => {
    expect(show(run(src, scopeOf()))).toEqual(expected);
  });
});

describe('where errors point', () => {
  const at = (src: string) => {
    const r = run(src, scopeOf());
    return r instanceof FormulaError ? r.at : 'no error';
  };
  test.each([
    ['1 +', 3],
    ['(1', 2],
    ['1)', 1],
    ['1 2', 2],
    ['"unclosed', 0],
    ['{unclosed', 0],
    ['1 @ 2', 2],
    ['nosuch(1)', 0],
    ['1 + nosuch(1)', 4],
    ['{Nope} + 1', 0],
    ['1 / 0', 2],
    ['round("x")', 0],
    ['if({Done})', 0],
  ])('%s', (src, pos) => {
    expect(at(src)).toBe(pos);
  });
});

describe('references and renaming', () => {
  const names = (src: string) => [...references(parse(src))].sort();
  test('references lists the properties a formula reads, lower-cased', () => {
    expect(names('{Price} * Quantity + prop("Due Date")')).toEqual(['due date', 'price', 'quantity']);
    expect(names('if({Done}, round({Score}, 1), "")')).toEqual(['done', 'score']);
    expect(names('1 + 2')).toEqual([]);
  });
  test.each([
    ['{Price} * 2', 'Price', 'Cost', '{Cost} * 2'],
    ['Price * 2', 'Price', 'Cost', '{Cost} * 2'],
    ['prop("Price") * 2', 'price', 'Cost', '{Cost} * 2'],
    ['{price} + {Price}', 'PRICE', 'A b', '{A b} + {A b}'],
    ['round({Price}, 2) + Quantity', 'Quantity', 'Qty', 'round({Price}, 2) + {Qty}'],
    ['if(Done, "x", "y")', 'Done', 'Finished', 'if({Finished}, "x", "y")'],
    ['{Price} and not {Done}', 'Done', 'Ok', '{Price} and not {Ok}'],
    ['round(1)', 'round', 'x', 'round(1)'],
    ['"Price" + {Cost}', 'Price', 'X', '"Price" + {Cost}'],
    ['{Other} + 1', 'Price', 'Cost', '{Other} + 1'],
    ['"unclosed', 'Price', 'Cost', '"unclosed'],
  ])('%s', (src, from, to, expected) => {
    expect(renameProperty(src, from, to)).toBe(expected);
  });
});

describe('the function table', () => {
  test('every function the engine had is still there, in its group', () => {
    const had: Record<string, string[]> = {
      logic: ['if', 'ifs', 'and', 'or', 'not', 'empty', 'ifEmpty'],
      math: ['round', 'floor', 'ceil', 'abs', 'sqrt', 'pow', 'mod', 'min', 'max', 'sum', 'average', 'toNumber'],
      text: ['concat', 'length', 'lower', 'upper', 'trim', 'contains', 'startsWith', 'endsWith', 'replace', 'slice', 'split', 'format', 'repeat'],
      dates: ['now', 'today', 'date', 'dateAdd', 'dateSubtract', 'dateBetween', 'daysUntil', 'formatDate', 'year', 'month', 'day', 'weekday', 'hour', 'minute'],
      lists: ['count', 'first', 'last', 'at', 'join', 'unique', 'sort'],
    };
    for (const [group, names] of Object.entries(had))
      for (const name of names) expect(FUNCTIONS[name.toLowerCase()]?.group, name).toBe(group);
  });
});
